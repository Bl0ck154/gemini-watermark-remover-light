import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const userscriptPath = path.join(root, 'gemini-watermark-remover-light.user.js');
const outputPath = path.join(root, 'docs', 'maps.js');
const source = fs.readFileSync(userscriptPath, 'utf8');
const match = source.match(/const EMBEDDED_ALPHA_MAPS_U8 = Object\.freeze\((\{[\s\S]*?\})\);/);

if (!match) throw new Error('Could not find embedded alpha maps in the userscript');

const generated = `// Generated by scripts/sync-docs-maps.mjs. Do not edit by hand.\nexport const EMBEDDED_ALPHA_MAPS_U8 = Object.freeze(${match[1]});\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    console.error('docs/maps.js is out of sync. Run: npm run sync:docs-maps');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, generated);
  console.log('Synced docs/maps.js from the userscript');
}
